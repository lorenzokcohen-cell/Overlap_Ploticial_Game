// Turns data/poll_data.json (sourced national polls) into supabase/seed.sql.
// Usage: npm run seed  → then paste supabase/seed.sql into the Supabase SQL Editor.
import fs from "node:fs";

const data = JSON.parse(fs.readFileSync(new URL("../data/poll_data.json", import.meta.url)));
const TOPICS = {
  "Government & elections": ["congress-term-limits","scotus-age-limit","popular-vote","voter-id","auto-voter-registration","stock-trading-ban","obey-supreme-court"],
  "Guns": ["guns-mental-illness","gun-age-21","teachers-carry-guns","concealed-carry-more-places"],
  "Energy & climate": ["more-solar","more-wind","more-nuclear","climate-gov-too-little"],
  "Tech & kids": ["phone-ban-class","phone-ban-all-day","social-media-under-16-ban","social-media-parental-consent","social-media-age-verification","social-media-time-limits","gov-restrict-false-info","tech-restrict-false-info","ai-more-concerned","trust-us-regulate-ai"],
  "Health & economy": ["extend-aca-credits","gov-health-coverage","drug-price-regulation","social-security-no-cuts","raise-corporate-taxes","raise-taxes-400k","gov-retirement-income","gov-internet-access"],
  "World": ["nato-commitment","russia-sanctions","ukraine-military-aid"],
  "Immigration": ["immigration-good-thing","deport-illegal-immigrants","deport-long-term-workers"],
  "Schools & rights": ["school-vouchers","school-book-lists","free-speech-important","free-press-important"],
};
const topicOf = Object.fromEntries(Object.entries(TOPICS).flatMap(([t, ids]) => ids.map((id) => [id, t])));
const q = (v) => (v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");

let sql = "-- Generated by scripts/build-seed.mjs. Safe to re-run: updates existing rows.\n\n";
sql += "insert into public.game_items (id, statement, original_wording, d, r, pollster, fielded, url, notes, topic) values\n";
sql += data.items.map((i) =>
  `  (${q(i.id)}, ${q(i.statement)}, ${q(i.original_wording)}, ${i.d}, ${i.r}, ${q(i.pollster)}, ${q(i.fielded)}, ${q(i.url)}, ${q(i.notes)}, ${q(topicOf[i.id] || "Other")})`
).join(",\n");
sql += "\non conflict (id) do update set statement=excluded.statement, original_wording=excluded.original_wording, d=excluded.d, r=excluded.r, pollster=excluded.pollster, fielded=excluded.fielded, url=excluded.url, notes=excluded.notes, topic=excluded.topic;\n\n";

// Overlap's own questionnaire mirrors the national items so community results can be compared with them.
sql += "insert into public.poll_questions (id, statement, topic, source_item_id, sort_order) values\n";
sql += data.items.map((i, k) => `  (${q(i.id)}, ${q(i.statement)}, ${q(topicOf[i.id] || "Other")}, ${q(i.id)}, ${k})`).join(",\n");
sql += "\non conflict (id) do update set statement=excluded.statement, topic=excluded.topic, source_item_id=excluded.source_item_id, sort_order=excluded.sort_order;\n";

fs.writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
const missing = data.items.filter((i) => !topicOf[i.id]).map((i) => i.id);
console.log(`Wrote ${data.items.length} items to supabase/seed.sql` + (missing.length ? `; no topic for: ${missing.join(", ")}` : ""));
